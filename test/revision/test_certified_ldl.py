"""Independent certificate, coverage, and differentiability regression tests."""
import itertools

import pytest
import torch

from models.certified_ldl import (
    assemble_lmi, contraction, inverse_contraction,
    inverse_residual_weights, residual_weights,
)

torch.set_num_threads(1)


def sample(dims, dtype=torch.float64, batch=()):
    torch.manual_seed(19)
    d0, *hidden, p = dims
    a = torch.randn(*batch, p, d0, dtype=dtype) * .4
    cs = [torch.randn(*batch, y, x, dtype=dtype) * .4
          for x, y in zip([d0] + hidden[:-1], hidden)]
    b = torch.randn(*batch, p, hidden[-1], dtype=dtype) * .4
    return a, cs, b


def test_legacy_cross_term_counterexample():
    a = torch.tensor([[.6]], dtype=torch.float64)
    cs = [torch.tensor([[.8]], dtype=torch.float64), torch.ones(1, 1, dtype=torch.float64)]
    b = a.clone()
    d1, d2 = .64, 1.
    j1, j2 = .36, .45
    legacy = 2 - .6**2 - j1**2/d1 - j2**2/d2 - 1/d2
    correct = 2 - .6**2 - j1**2/d1 - (j2+1)**2/d2
    assert legacy > 0 and correct == pytest.approx(-.665)
    assert torch.linalg.eigvalsh(assemble_lmi(a, cs, b)).min() < -.09
    assert (.6 + .6 * .8) > 1


@pytest.mark.parametrize('dims', [(2, 3, 4), (3, 2, 5, 2), (2, 5, 3, 4, 1)])
@pytest.mark.parametrize('dtype', [torch.float32, torch.float64, torch.complex128])
def test_soundness_and_inverse(dims, dtype):
    a, cs, b = sample(dims, dtype)
    lam = [torch.linspace(.7, 1.4, c.shape[-2], dtype=a.real.dtype) for c in cs]
    w = residual_weights(a, cs, b, bound=1.7, multipliers=lam)
    m = assemble_lmi(w.a, w.cs, w.b, bound=1.7, multipliers=lam)
    assert torch.linalg.eigvalsh(m).min() > 0
    recovered = inverse_residual_weights(w.a, w.cs, w.b, bound=1.7, multipliers=lam)
    v = residual_weights(*recovered, bound=1.7, multipliers=lam)
    tol = 3e-5 if dtype == torch.float32 else 1e-10
    for x, y in zip((w.a, *w.cs, w.b), (v.a, *v.cs, v.b)):
        torch.testing.assert_close(x, y, atol=tol, rtol=tol)


def test_coverage_for_independently_feasible_weights():
    # These weights were not generated by the parameterization. The inverse
    # must reconstruct them whenever the original LMI is strictly feasible.
    a, cs, b = sample((3, 2, 4, 2))
    a, cs, b = a*.2, [c*.2 for c in cs], b*.2
    assert torch.linalg.eigvalsh(assemble_lmi(a, cs, b)).min() > 0
    raw = inverse_residual_weights(a, cs, b)
    w = residual_weights(*raw)
    for x, y in zip((a, *cs, b), (w.a, *w.cs, w.b)):
        torch.testing.assert_close(x, y, atol=1e-12, rtol=1e-12)


def test_batched_frequency_matrices():
    w = residual_weights(*sample((2, 3, 2, 2), torch.complex128, (5,)))
    assert torch.linalg.eigvalsh(assemble_lmi(w.a, w.cs, w.b)).min() > 0


def test_all_relu_jacobians_small_network():
    w = residual_weights(*sample((2, 2, 2, 2)))
    for bits in itertools.product([0., 1.], repeat=4):
        s1 = torch.diag(torch.tensor(bits[:2], dtype=torch.float64))
        s2 = torch.diag(torch.tensor(bits[2:], dtype=torch.float64))
        jac = w.a + w.b @ s2 @ w.cs[1] @ s1 @ w.cs[0]
        assert torch.linalg.matrix_norm(jac, ord=2) <= 1 + 1e-12


def test_gradients():
    raw = sample((2, 2, 2))
    args = tuple(t.requires_grad_() for t in (raw[0], raw[1][0], raw[2]))
    def fn(a, c, b):
        w = residual_weights(a, [c], b)
        return torch.cat([w.a.flatten(), w.cs[0].flatten(), w.b.flatten()])
    assert torch.autograd.gradcheck(fn, args, atol=1e-5)


def test_contraction_inverse_and_boundary_failure():
    w = torch.tensor([[1., 2.], [3., -1.]], dtype=torch.float64)
    q = contraction(w, 2.)
    torch.testing.assert_close(inverse_contraction(q, 2.), w)
    with pytest.raises(torch.linalg.LinAlgError):
        inverse_contraction(torch.eye(2, dtype=torch.float64))


def test_cancellation_allows_larger_last_hidden_weight():
    # With one hidden layer Z=L^2 I, independently of A. A near-unit skip
    # therefore need not force C to vanish, unlike the discarded-cross-term rule.
    raw = (torch.tensor([[10.]], dtype=torch.float64),
           [torch.tensor([[1.]], dtype=torch.float64)],
           torch.tensor([[0.]], dtype=torch.float64))
    w = residual_weights(*raw)
    assert w.cs[0].item() == pytest.approx(1.)
    assert (w.cs[0] @ torch.linalg.solve(w.leading_pivots[0], w.cs[0].T)).item() > 2
    assert torch.linalg.eigvalsh(assemble_lmi(w.a, w.cs, w.b)).min() > 0


def test_structured_boundary_approximation():
    # Boundary certificate for the identity map with a disconnected hidden unit.
    a = torch.eye(2, dtype=torch.float64)
    c = torch.zeros(1, 2, dtype=torch.float64)
    b = torch.zeros(2, 1, dtype=torch.float64)
    assert torch.linalg.eigvalsh(assemble_lmi(a, [c], b)).min() == 0
    for t in (.5, .99, .999999):
        m = assemble_lmi(t*a, [t*c], t*b)
        assert torch.linalg.eigvalsh(m).min() > 0
        raw = inverse_residual_weights(t*a, [t*c], t*b)
        w = residual_weights(*raw)
        torch.testing.assert_close(w.a, t*a)

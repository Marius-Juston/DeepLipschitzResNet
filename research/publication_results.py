"""Regenerate publication tables and vector figures from the completed campaign.

Run with uv run --locked python research/publication_results.py.
No training source or frozen campaign artifact is modified.
"""
import csv
import hashlib
import itertools
import json
from pathlib import Path
import statistics

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import wilcoxon

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT/'runs/revision_campaign'
PAPER = ROOT.parent/'LDL-Lipschitz-ResNet-LMI'
OUT = ROOT/'revision_artifacts/publication_results'
ALGS = ['ldlt-resnet','ldlt','sandwich','sdp','aol','ortho']
NAMES = dict(zip(ALGS,['LDL residual','LDL sequential','Sandwich','SLL','AOL','Orthogonal']))
METRICS = ['mean_test_acc',*[f'mean_cert_acc_{r}' for r in (36,72,108,255)]]


def holm(values):
    order=np.argsort(values);out=np.empty(len(values));previous=0.
    for rank,index in enumerate(order):
        previous=max(previous,min(1.,values[index]*(len(values)-rank)))
        out[index]=previous
    return out.tolist()


def table(name,head,rows,alignment):
    text=['% Generated by research/publication_results.py; do not edit numbers.',
          r'\begin{tabular}{'+alignment+'}',r'\toprule',head+r' \\',r'\midrule']
    text += [' & '.join(row)+r' \\' for row in rows]
    text += [r'\bottomrule',r'\end{tabular}']
    (PAPER/'result_tables'/name).write_text('\n'.join(text)+'\n')


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    (PAPER/'result_tables').mkdir(exist_ok=True)
    manifest=json.loads((RUN/'manifest.json').read_text())
    digest=hashlib.sha256()
    for p in sorted([*ROOT.glob('src/**/*.py'),ROOT/'revision_experiments.py',ROOT/'uv.lock']):
        digest.update(str(p.relative_to(ROOT)).encode());digest.update(p.read_bytes())
    assert digest.hexdigest()==manifest['code_sha256'],'Training source differs from manifest'
    uci={};images={};records=[];audits=[];provenance={}
    for job in manifest['jobs']:
        p=RUN/'jobs'/job['id']/'result.json';raw=p.read_bytes();r=json.loads(raw)
        assert r['job']==job and r['code_sha256']==manifest['code_sha256'],p
        provenance[job['id']]=hashlib.sha256(raw).hexdigest()
        if job['kind']=='uci':
            assert r['n_folds']==4 and len(r['fold_results'])==4
            for f in r['fold_results']:
                assert f['split_policy']=='test_mask_one'
                if job['algorithm'].startswith('ldlt'):
                    audits.append(f['certificate_audit']['min_eigenvalue'])
            for metric in METRICS:
                actual=statistics.mean(f['test_acc'] if metric=='mean_test_acc' else
                                       f['cert_evals'][metric.rsplit('_',1)[1]] for f in r['fold_results'])
                assert abs(actual-r[metric])<1e-12
            uci[job['dataset'],job['algorithm'],job['loss']]=r
            records.append(dict(dataset=job['dataset'],algorithm=job['algorithm'],loss=job['loss'],
                                **{metric:r[metric] for metric in METRICS},
                                parameters=r['fold_results'][0]['parameters']))
        else:
            images.setdefault((job['algorithm'],job['loss']),[]).append(r)
            for a in r['certificate_audits']:audits.append(a['min_eigenvalue'])
    assert len(provenance)==792 and all(np.isfinite(v) and v>0 for v in audits)
    datasets=sorted({d for d,a,l in uci if l=='ce'})
    assert len(datasets)==121
    with (OUT/'uci_dataset_means.csv').open('w') as f:
        writer=csv.DictWriter(f,fieldnames=list(records[0]));writer.writeheader();writer.writerows(records)
    values={metric:{a:np.array([uci[d,a,'ce'][metric] for d in datasets]) for a in ALGS}
            for metric in METRICS}
    tests=[]
    for metric,vs in values.items():
        rows=[]
        for a,b in itertools.combinations(ALGS,2):
            diff=vs[a]-vs[b]
            p=1. if np.all(diff==0) else float(wilcoxon(diff,zero_method='wilcox').pvalue)
            rows.append(dict(metric=metric,a=a,b=b,p=p,mean_difference=float(diff.mean()),
                             wins=int((diff>0).sum()),ties=int((diff==0).sum()),losses=int((diff<0).sum())))
        for row,adjusted in zip(rows,holm([r['p'] for r in rows])):row['holm_within_metric']=adjusted
        tests.extend(rows)
    for row,adjusted in zip(tests,holm([r['p'] for r in tests])):row['holm_all_75']=adjusted
    uci_rows=[[NAMES[a],*[f'{100*values[m][a].mean():.2f}' for m in METRICS]] for a in ALGS]
    table('uci.tex',r'Method & Clean & $36/255$ & $72/255$ & $108/255$ & $1$',uci_rows,'lrrrrr')
    comparisons=[r for r in tests if r['a']=='ldlt-resnet' and r['b']=='sandwich']
    table('paired.tex',r'Metric & Difference (pp) & $p_{15}$ & $p_{75}$',
          [[label,f"{100*r['mean_difference']:+.2f}",f"{r['holm_within_metric']:.3f}",f"{r['holm_all_75']:.3f}"]
           for label,r in zip(['Clean','$36/255$','$72/255$','$108/255$','$1$'],comparisons)],'lrrr')
    image_rows=[];image_summary=[]
    for alg in ['ldlt-resnet','sandwich','sdp']:
        for loss in ['ce','margin']:
            rs=images[alg,loss];assert sorted(r['seed'] for r in rs)==[42,43,44]
            v=[[r['metrics']['clean'],*[r['metrics']['certified'][str(e)] for e in (36,72,108)]] for r in rs]
            v=np.array(v)*100
            image_rows.append([NAMES[alg],loss.upper() if loss=='ce' else 'Margin',
                               *[f'${m:.2f}\\pm{s:.2f}$' for m,s in zip(v.mean(0),v.std(0,ddof=1))]])
            image_summary.append(dict(algorithm=alg,loss=loss,mean_percent=v.mean(0).tolist(),sd_percent=v.std(0,ddof=1).tolist()))
    table('cifar10.tex',r'Method & Loss & Clean & $36/255$ & $72/255$ & $108/255$',image_rows,'llrrrr')
    margin_rows=[];margin=[]
    for alg in ALGS[:4]:
        means={}
        for loss in ['ce','margin']:
            means[loss]=[100*statistics.mean(uci[d,alg,loss][metric] for d in manifest['uci_ablation_datasets'])
                         for metric in METRICS]
        margin.append(dict(algorithm=alg,**means))
        margin_rows.append([NAMES[alg],f"{means['ce'][0]:.2f}",f"{means['margin'][0]:.2f}",
                            f"{means['ce'][2]:.2f}",f"{means['margin'][2]:.2f}"])
    table('margin.tex',r'Method & CE clean & Margin clean & CE cert. & Margin cert.',margin_rows,'lrrrr')
    profile=json.loads((RUN/'profile_gpu.json').read_text())
    profile_rows=[]
    for alg in ['ldlt-resnet','sandwich','sdp']:
        p=next(r for r in profile['rows'] if r['name']=='image-'+alg)
        rs=images[alg,'ce']+images[alg,'margin']
        seconds=[r['elapsed_seconds_this_session'] for r in rs]
        profile_rows.append([NAMES[alg],f"{rs[0]['parameters']:,}",f"{1000*p['median_forward_backward_seconds']:.2f}",
                             f"{p['peak_allocated_bytes']/2**20:.1f}",f"{statistics.median(seconds)/60:.1f}"])
    table('cost.tex',r'Method & Parameters & Fwd/bwd (ms) & Peak (MiB) & Run (min)',profile_rows,'lrrrr')
    summary=dict(source_sha256=manifest['code_sha256'],result_sha256=provenance,
                 uci_means={m:{a:float(v.mean()) for a,v in vs.items()} for m,vs in values.items()},
                 paired_tests=tests,cifar=image_summary,margin=margin,
                 recorded_positive_ldl_audits=len(audits),min_recorded_eigenvalue=min(audits),
                 statistics='Two-sided Wilcoxon across 121 dataset means; Holm across 15 pairs per metric AND across all 75 tests. No independent-seed claim for UCI.',
                 limitation='Saved diagnostics are not interval certificates or independent checkpoint reevaluation.')
    (OUT/'summary.json').write_text(json.dumps(summary,indent=2,allow_nan=False)+'\n')
    plt.rcParams.update({'pdf.fonttype':42,'font.size':9,'axes.spines.top':False,'axes.spines.right':False})
    colors=['#0072B2','#D55E00','#009E73','#CC79A7']
    fig,axes=plt.subplots(1,2,figsize=(8.1,3.0),layout='constrained')
    for alg,color in zip(ALGS[:4],colors):
        axes[0].plot([0,36/255,72/255,108/255,1],[100*values[m][alg].mean() for m in METRICS],
                     '-o',ms=3,label=NAMES[alg],color=color)
    axes[0].set(xlabel='Radius in standardized feature coordinates',ylabel='Accuracy (%)',title='UCI: 121 datasets, CE')
    axes[0].legend(fontsize=7)
    for alg,color in zip(['ldlt-resnet','sandwich','sdp'],[colors[0],colors[2],colors[3]]):
        row=next(r for r in image_summary if r['algorithm']==alg and r['loss']=='margin')
        axes[1].errorbar([0,36/255,72/255,108/255],row['mean_percent'],yerr=row['sd_percent'],
                         fmt='-o',ms=3,capsize=2,label=NAMES[alg],color=color)
    axes[1].set(xlabel='Radius in raw pixel coordinates',ylabel='Accuracy (%)',title='CIFAR-10: margin training, three seeds')
    axes[1].legend(fontsize=7)
    for ax in axes:ax.grid(alpha=.2)
    fig.savefig(PAPER/'Figures/revision/accuracy_results.pdf');plt.close(fig)
    fig,ax=plt.subplots(figsize=(5.7,3.1),layout='constrained')
    for alg,color in zip(ALGS[:4],colors):
        x=values['mean_test_acc'][alg]-values['mean_test_acc']['sandwich']
        y=values['mean_cert_acc_108'][alg]-values['mean_cert_acc_108']['sandwich']
        if alg=='ldlt-resnet':
            ax.scatter(100*x,100*y,s=12,alpha=.65,color=color)
    ax.axhline(0,color='gray',lw=.7);ax.axvline(0,color='gray',lw=.7)
    ax.set(xlabel='Clean accuracy difference (percentage points)',
           ylabel='Certified accuracy difference (pp)',title='LDL residual minus Sandwich: one point per UCI dataset')
    fig.savefig(PAPER/'Figures/revision/uci_paired_tradeoff.pdf');plt.close(fig)
    print(json.dumps(dict(comparisons=comparisons,margin=margin,image_cost_rows=profile_rows),indent=2))


if __name__=='__main__':main()
